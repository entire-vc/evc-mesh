package domain

import (
	"errors"
	"regexp"
	"sort"
	"unicode/utf8"
)

// MaxIconValueBytes bounds the longest accepted icon value (a ZWJ family
// sequence of four people with skin tones fits well under it).
const MaxIconValueBytes = 64

// ErrInvalidIconValue is returned by ValidateIconValue.
var ErrInvalidIconValue = errors.New("icon must be a single emoji, icon:<name> or empty")

// iconNamePattern is the name part of an `icon:<name>` value.
var iconNamePattern = regexp.MustCompile(`^[a-z0-9-]{1,40}$`)

// ValidateIconValue checks an entity icon value as the picker stores it:
//
//   - ""            no icon, the entity's default is drawn;
//   - "🚀"          exactly one emoji grapheme;
//   - "icon:rocket" a named icon, name matching [a-z0-9-]{1,40}.
//
// Anything else (free text, markup, two graphemes) is rejected. Callers that
// must keep legacy text values readable (projects.icon) compare with the
// stored value first and validate only a changed one.
func ValidateIconValue(s string) error {
	if s == "" {
		return nil
	}
	if len(s) > MaxIconValueBytes || !utf8.ValidString(s) {
		return ErrInvalidIconValue
	}
	if len(s) > 5 && s[:5] == "icon:" {
		if iconNamePattern.MatchString(s[5:]) {
			return nil
		}
		return ErrInvalidIconValue
	}
	if isSingleEmojiGrapheme(s) {
		return nil
	}
	return ErrInvalidIconValue
}

// isSingleEmojiGrapheme reports whether s is exactly one emoji grapheme: a
// pictograph (with optional VS16 / skin tone), a keycap sequence, a flag (two
// regional indicators), a tag-sequence flag, or ZWJ-joined pictographs.
func isSingleEmojiGrapheme(s string) bool {
	rs := []rune(s)
	if len(rs) == 0 {
		return false
	}
	i := 0

	// Keycap: [0-9#*] VS16? U+20E3
	if isKeycapBase(rs[0]) {
		i = 1
		if i < len(rs) && rs[i] == 0xFE0F {
			i++
		}
		return i == len(rs)-1 && rs[i] == 0x20E3
	}

	// Flag: two regional indicators.
	if isRegionalIndicator(rs[0]) {
		return len(rs) == 2 && isRegionalIndicator(rs[1])
	}

	for {
		if i >= len(rs) || !isPictographic(rs[i]) {
			return false
		}
		i++
		// Modifiers on this element: VS16, skin tone, tag sequence.
		for i < len(rs) {
			r := rs[i]
			if r == 0xFE0F || (r >= 0x1F3FB && r <= 0x1F3FF) || (r >= 0xE0020 && r <= 0xE007F) {
				i++
				continue
			}
			break
		}
		if i == len(rs) {
			return true
		}
		if rs[i] != 0x200D { // ZWJ must join the next pictograph
			return false
		}
		i++
	}
}

func isKeycapBase(r rune) bool {
	return (r >= '0' && r <= '9') || r == '#' || r == '*'
}

func isRegionalIndicator(r rune) bool { return r >= 0x1F1E6 && r <= 0x1F1FF }

// isPictographic reports whether r is an emoji base: a code point with the
// Unicode Emoji property (emoji-data.txt, Unicode 16.0), less ASCII keycap
// bases, regional indicators and skin-tone modifiers, which have their own
// positions in a grapheme. Plain symbols from the same blocks (U+2630 ☰,
// U+1F650 ornaments, mahjong tiles but 🀄) are not emoji and are refused.
func isPictographic(r rune) bool {
	i := sort.Search(len(emojiBases), func(i int) bool { return emojiBases[i][1] >= r })
	return i < len(emojiBases) && emojiBases[i][0] <= r
}

