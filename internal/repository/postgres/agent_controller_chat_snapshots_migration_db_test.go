//go:build integration

package postgres

import (
	"context"
	"database/sql"
	"os"
	"path/filepath"
	"testing"

	"github.com/jmoiron/sqlx"
	"github.com/pressly/goose/v3"
	"github.com/stretchr/testify/require"
)

// TestAgentControllerChatSnapshotsMigrationDownUp runs only this migration in a
// throwaway schema: up creates the table, down removes it, up again restores it.
func TestAgentControllerChatSnapshotsMigrationDownUp(t *testing.T) {
	const schema = "chat_snapshots_migration_test"
	const file = "20261111100_agent_controller_chat_snapshots.sql"
	lockDB := testDB(t)
	var migrationDB *sqlx.DB
	lock, err := lockDB.BeginTxx(context.Background(), nil)
	require.NoError(t, err)
	_, err = lock.Exec(`SELECT pg_advisory_xact_lock(90304261110100)`)
	require.NoError(t, err)
	t.Cleanup(func() {
		if migrationDB != nil {
			_ = migrationDB.Close()
		}
		if _, cleanupErr := lockDB.Exec(`DROP SCHEMA IF EXISTS ` + schema + ` CASCADE`); cleanupErr != nil {
			t.Errorf("drop isolated migration schema: %v", cleanupErr)
		}
		if cleanupErr := lock.Rollback(); cleanupErr != nil && cleanupErr != sql.ErrTxDone {
			t.Errorf("release isolated migration test lock: %v", cleanupErr)
		}
	})
	_, err = lockDB.Exec(`DROP SCHEMA IF EXISTS ` + schema + ` CASCADE; CREATE SCHEMA ` + schema)
	require.NoError(t, err)

	migrationDB = testDB(t)
	migrationDB.SetMaxOpenConns(1)
	_, err = migrationDB.Exec(`SELECT set_config('search_path', '` + schema + `', false)`)
	require.NoError(t, err)
	_, err = migrationDB.Exec(`
		CREATE TABLE agents (id uuid PRIMARY KEY);
		CREATE TABLE goose_db_version (
			id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
			version_id bigint NOT NULL,
			is_applied boolean NOT NULL,
			tstamp timestamp NOT NULL DEFAULT now()
		);
		INSERT INTO goose_db_version (version_id, is_applied) VALUES (20261108100, true);
	`)
	require.NoError(t, err)

	migration, err := os.ReadFile("../../../migrations/" + file)
	require.NoError(t, err)
	dir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(dir, file), migration, 0600))
	require.NoError(t, goose.SetDialect("postgres"))

	present := func() bool {
		var ok bool
		require.NoError(t, migrationDB.Get(&ok, `SELECT to_regclass('`+schema+`.agent_controller_chat_snapshots') IS NOT NULL`))
		return ok
	}
	require.NoError(t, goose.Up(migrationDB.DB, dir))
	require.EqualValues(t, 20261111100, gooseVersion(t, migrationDB.DB))
	require.True(t, present())
	// The array check holds: a non-array sessions value is refused.
	_, err = migrationDB.Exec(`INSERT INTO agents VALUES ('00000000-0000-0000-0000-000000000001')`)
	require.NoError(t, err)
	_, err = migrationDB.Exec(`INSERT INTO agent_controller_chat_snapshots (agent_id, runner_id, sessions, reported_at)
		VALUES ('00000000-0000-0000-0000-000000000001', 'r', '{}'::jsonb, now())`)
	require.Error(t, err)

	require.NoError(t, goose.Down(migrationDB.DB, dir))
	require.EqualValues(t, 20261108100, gooseVersion(t, migrationDB.DB))
	require.False(t, present())

	require.NoError(t, goose.Up(migrationDB.DB, dir))
	require.EqualValues(t, 20261111100, gooseVersion(t, migrationDB.DB))
	require.True(t, present())
}
