// TestStartAfterProvenanceMigrationDownUpIsolated: dates that exist before
// the migration become legacy_unknown without a version bump, survive the
// downgrade, and are marked again on the next Up.
func TestStartAfterProvenanceMigrationDownUpIsolated(t *testing.T) {
	lockDB := testDB(t)
	var migrationDB *sqlx.DB
	lock, err := lockDB.BeginTxx(context.Background(), nil)
	require.NoError(t, err)
	_, err = lock.Exec(`SELECT pg_advisory_xact_lock(90304261028400)`)
	require.NoError(t, err)
	t.Cleanup(func() {
		if migrationDB != nil {
			_ = migrationDB.Close()
		}
		if _, cleanupErr := lockDB.Exec(`DROP SCHEMA IF EXISTS start_after_migration_test CASCADE`); cleanupErr != nil {
			t.Errorf("drop isolated start_after migration schema: %v", cleanupErr)
		}
		if cleanupErr := lock.Rollback(); cleanupErr != nil && cleanupErr != sql.ErrTxDone {
			t.Errorf("release isolated migration test lock: %v", cleanupErr)
		}
	})

	_, err = lockDB.Exec(`DROP SCHEMA IF EXISTS start_after_migration_test CASCADE; CREATE SCHEMA start_after_migration_test`)
	require.NoError(t, err)

	migrationDB = testDB(t)
	migrationDB.SetMaxOpenConns(1)
	_, err = migrationDB.Exec(`SELECT set_config('search_path', 'start_after_migration_test,public', false)`)
	require.NoError(t, err)
	_, err = migrationDB.Exec(`
		CREATE TABLE tasks (id uuid PRIMARY KEY, start_after timestamptz, version bigint NOT NULL DEFAULT 1);
		CREATE FUNCTION advance_task_version() RETURNS trigger
			LANGUAGE plpgsql AS $$ BEGIN NEW.version := OLD.version + 1; RETURN NEW; END $$;
		CREATE TRIGGER task_version_before_update BEFORE UPDATE ON tasks
			FOR EACH ROW EXECUTE FUNCTION advance_task_version();
		INSERT INTO tasks (id, start_after) VALUES
			('00000000-0000-0000-0000-00000000000a', '2026-11-01T06:00:00Z'),
			('00000000-0000-0000-0000-00000000000b', NULL);
		CREATE TABLE goose_db_version (
			id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
			version_id bigint NOT NULL,
			is_applied boolean NOT NULL,
			tstamp timestamp NOT NULL DEFAULT now()
		);
		INSERT INTO goose_db_version (version_id, is_applied) VALUES (20261028300, true);
	`)
	require.NoError(t, err)

	const name = "20261028400_task_start_after_provenance.sql"
	migration, err := os.ReadFile("../../../migrations/" + name)
	require.NoError(t, err)
	migrationsDir, err := os.MkdirTemp("", "start-after-migration-")
	require.NoError(t, err)
	require.NoError(t, os.WriteFile(filepath.Join(migrationsDir, name), migration, 0600))
	t.Cleanup(func() {
		if cleanupErr := os.RemoveAll(migrationsDir); cleanupErr != nil {
			t.Errorf("remove isolated migration files: %v", cleanupErr)
		}
	})
	require.NoError(t, goose.SetDialect("postgres"))

	require.NoError(t, goose.Up(migrationDB.DB, migrationsDir))
	require.EqualValues(t, 20261028400, gooseVersion(t, migrationDB.DB))
	assertStartAfterMigrated(t, migrationDB, true)

	require.NoError(t, goose.Down(migrationDB.DB, migrationsDir))
	require.EqualValues(t, 20261028300, gooseVersion(t, migrationDB.DB))
	assertStartAfterMigrated(t, migrationDB, false)

	require.NoError(t, goose.Up(migrationDB.DB, migrationsDir))
	require.EqualValues(t, 20261028400, gooseVersion(t, migrationDB.DB))
	assertStartAfterMigrated(t, migrationDB, true)

	// The version trigger is back on after the marking.
	_, err = migrationDB.Exec(`UPDATE tasks SET start_after = NULL, start_after_origin = NULL WHERE id = '00000000-0000-0000-0000-00000000000a'`)
	require.NoError(t, err)
	var version int64
	require.NoError(t, migrationDB.Get(&version, `SELECT version FROM tasks WHERE id = '00000000-0000-0000-0000-00000000000a'`))
	require.EqualValues(t, 2, version)
}

func assertStartAfterMigrated(t *testing.T, db *sqlx.DB, up bool) {
	t.Helper()
	var date string
	var version int64
	require.NoError(t, db.QueryRow(`SELECT to_char(start_after AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'), version
		FROM tasks WHERE id = '00000000-0000-0000-0000-00000000000a'`).Scan(&date, &version))
	require.Equal(t, "2026-11-01T06:00:00Z", date, "the date is kept")
	require.EqualValues(t, 1, version, "marking is not a task change")

	var column bool
	require.NoError(t, db.Get(&column, `SELECT EXISTS (SELECT 1 FROM information_schema.columns
		WHERE table_schema = 'start_after_migration_test' AND table_name = 'tasks' AND column_name = 'start_after_origin')`))
	require.Equal(t, up, column, "start_after_origin presence")
	if !up {
		return
	}
	origins := map[string]sql.NullString{}
	rows, err := db.Query(`SELECT id::text, start_after_origin FROM tasks`)
	require.NoError(t, err)
	defer rows.Close()
	for rows.Next() {
		var id string
		var origin sql.NullString
		require.NoError(t, rows.Scan(&id, &origin))
		origins[id] = origin
	}
	require.NoError(t, rows.Err())
	require.Equal(t, "legacy_unknown", origins["00000000-0000-0000-0000-00000000000a"].String)
	require.False(t, origins["00000000-0000-0000-0000-00000000000b"].Valid, "no date, no origin")
}
