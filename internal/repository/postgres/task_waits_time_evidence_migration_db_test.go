// TestTaskWaitsTimeEvidenceLegacyMigrationDownUpIsolated: a time wait
// declared before evidence was required cannot be resolved once 20261029100
// is in (its NOT VALID check still applies to the UPDATE); after 20261029200
// it is marked legacy and resolves, and the downgrade puts the old shape back.
func TestTaskWaitsTimeEvidenceLegacyMigrationDownUpIsolated(t *testing.T) {
	const schema = "task_waits_legacy_migration_test"
	lockDB := testDB(t)
	var migrationDB *sqlx.DB
	lock, err := lockDB.BeginTxx(context.Background(), nil)
	require.NoError(t, err)
	_, err = lock.Exec(`SELECT pg_advisory_xact_lock(90304261029200)`)
	require.NoError(t, err)
	t.Cleanup(func() {
		if migrationDB != nil {
			_ = migrationDB.Close()
		}
		if _, cleanupErr := lockDB.Exec(`DROP SCHEMA IF EXISTS ` + schema + ` CASCADE`); cleanupErr != nil {
			t.Errorf("drop isolated task_waits migration schema: %v", cleanupErr)
		}
		if cleanupErr := lock.Rollback(); cleanupErr != nil && cleanupErr != sql.ErrTxDone {
			t.Errorf("release isolated migration test lock: %v", cleanupErr)
		}
	})

	_, err = lockDB.Exec(`DROP SCHEMA IF EXISTS ` + schema + ` CASCADE; CREATE SCHEMA ` + schema)
	require.NoError(t, err)

	migrationDB = testDB(t)
	migrationDB.SetMaxOpenConns(1)
	_, err = migrationDB.Exec(`SELECT set_config('search_path', '` + schema + `,public', false)`)
	require.NoError(t, err)
	// The columns the two migrations and Resolve touch, and one time wait and
	// one card wait as they stood before evidence was required.
	_, err = migrationDB.Exec(`
		CREATE TABLE task_waits (
			id          uuid PRIMARY KEY,
			kind        text NOT NULL,
			until_at    timestamptz,
			resolved_at timestamptz,
			resolution  text
		);
		INSERT INTO task_waits (id, kind, until_at) VALUES
			('00000000-0000-0000-0000-00000000000a', 'time', now() + interval '1 hour'),
			('00000000-0000-0000-0000-00000000000b', 'card', NULL);
		CREATE TABLE start_after_receipts (
			id              uuid PRIMARY KEY,
			op              text NOT NULL,
			origin          text NOT NULL,
			source_offset   text,
			event_ref       text,
			evidence_source text,
			evidence_why    text,
			evidence_status text
		);
		CREATE TABLE goose_db_version (
			id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
			version_id bigint NOT NULL,
			is_applied boolean NOT NULL,
			tstamp timestamp NOT NULL DEFAULT now()
		);
		INSERT INTO goose_db_version (version_id, is_applied) VALUES (20261028100, true);
	`)
	require.NoError(t, err)

	migrationsDir, err := os.MkdirTemp("", "task-waits-legacy-migration-")
	require.NoError(t, err)
	t.Cleanup(func() {
		if cleanupErr := os.RemoveAll(migrationsDir); cleanupErr != nil {
			t.Errorf("remove isolated migration files: %v", cleanupErr)
		}
	})
	for _, name := range []string{"20261029100_task_waits_time_evidence.sql", "20261029200_task_waits_time_evidence_legacy.sql"} {
		migration, readErr := os.ReadFile("../../../migrations/" + name)
		require.NoError(t, readErr)
		require.NoError(t, os.WriteFile(filepath.Join(migrationsDir, name), migration, 0600))
	}
	require.NoError(t, goose.SetDialect("postgres"))

	legacy := uuid.MustParse("00000000-0000-0000-0000-00000000000a")
	waits := NewTaskWaitRepo(migrationDB)
	ctx := context.Background()

	// The state main is in: the old wait cannot be resolved.
	require.NoError(t, goose.UpTo(migrationDB.DB, migrationsDir, 20261029100))
	_, err = waits.Resolve(ctx, legacy, domain.WaitResolutionSuperseded)
	require.Error(t, err, "20261029100 alone refuses to resolve a pre-existing time wait")

	require.NoError(t, goose.Up(migrationDB.DB, migrationsDir))
	require.EqualValues(t, 20261029200, gooseVersion(t, migrationDB.DB))
	require.Equal(t, "legacy", evidenceStatus(t, migrationDB, "00000000-0000-0000-0000-00000000000a"))
	require.Empty(t, evidenceStatus(t, migrationDB, "00000000-0000-0000-0000-00000000000b"), "only time waits are marked")
	_, err = migrationDB.Exec(`INSERT INTO task_waits (id, kind, until_at, evidence_status)
		VALUES (gen_random_uuid(), 'time', now(), 'legacy')`)
	require.Error(t, err, "a new wait cannot be legacy")
	_, err = migrationDB.Exec(`INSERT INTO start_after_receipts (id, op, origin, source_offset, event_ref, evidence_source, evidence_why)
		VALUES (gen_random_uuid(), 'set', 'agent_evidence', 'Z', 'e', 'https://ci.example/s', 'the export starts then')`)
	require.Error(t, err, "an agent receipt without a status is refused")

	require.NoError(t, goose.Down(migrationDB.DB, migrationsDir))
	require.EqualValues(t, 20261029100, gooseVersion(t, migrationDB.DB))
	require.Empty(t, evidenceStatus(t, migrationDB, "00000000-0000-0000-0000-00000000000a"), "down restores the old shape")

	require.NoError(t, goose.Up(migrationDB.DB, migrationsDir))
	require.Equal(t, "legacy", evidenceStatus(t, migrationDB, "00000000-0000-0000-0000-00000000000a"))
	resolved, err := waits.Resolve(ctx, legacy, domain.WaitResolutionSuperseded)
	require.NoError(t, err)
	require.True(t, resolved, "a legacy time wait resolves")
}

func evidenceStatus(t *testing.T, db *sqlx.DB, id string) string {
	t.Helper()
	var status sql.NullString
	require.NoError(t, db.Get(&status, `SELECT evidence_status FROM task_waits WHERE id = $1`, id))
	return status.String
}
