#!/usr/bin/env node
/**
 * Writes web/public/theme-shared/*.js: the modules the import map in index.html
 * hands to theme bundles. Each shim re-exports from window.__MESH_SHARED__
 * (assigned by src/core/themes/shared.ts), so a bundle's `import ... from
 * "react"` gets the core's one copy of React.
 *
 *   node scripts/gen-theme-shims.mjs          write
 *   node scripts/gen-theme-shims.mjs --check  exit 1 if the committed files are stale (CI)
 */
import { createRequire } from "node:module";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import path from "node:path";

const WEB = path.join(import.meta.dirname, "..");
const OUT = path.join(WEB, "public", "theme-shared");
const require = createRequire(import.meta.url);
const check = process.argv.includes("--check");

const ident = /^[A-Za-z_$][\w$]*$/;
const names = (mod) => Object.keys(mod).filter((k) => ident.test(k) && k !== "default").sort();

// The names a theme can import from the SDK: its runtime exports (index.ts re-exports and consts,
// `export declare` in runtime.ts). Types have no runtime and are skipped.
function sdkNames() {
  const dir = path.join(import.meta.dirname, "..", "..", "packages", "mesh-theme-sdk", "src");
  const index = readFileSync(path.join(dir, "index.ts"), "utf8");
  const runtime = readFileSync(path.join(dir, "runtime.ts"), "utf8");
  const out = new Set();
  for (const m of index.matchAll(/^export\s*\{([^}]*)\}\s*from/gm)) {
    for (const part of m[1].split(",")) {
      const n = part.trim().split(/\s+as\s+/).pop();
      if (n) out.add(n);
    }
  }
  for (const m of index.matchAll(/^export\s+const\s+(\w+)/gm)) out.add(m[1]);
  for (const m of runtime.matchAll(/^export\s+declare\s+(?:function|const)\s+(\w+)/gm)) out.add(m[1]);
  return [...out].sort();
}

// key in SHARED_MODULES -> [file, export names]
const MODULES = {
  react: ["react.js", names(require("react"))],
  "react-dom": ["react-dom.js", names(require("react-dom"))],
  "react/jsx-runtime": ["jsx-runtime.js", names(require("react/jsx-runtime"))],
  "react-i18next": ["react-i18next.js", names(require("react-i18next"))],
  "@entire-vc/mesh-theme-sdk": ["mesh-theme-sdk.js", sdkNames()],
};

export const IMPORT_MAP = {
  imports: Object.fromEntries(Object.entries(MODULES).map(([k, [f]]) => [k, `/theme-shared/${f}`])),
};

let stale = 0;
for (const [key, [file, exports]] of Object.entries(MODULES)) {
  const body =
    `// Generated by scripts/gen-theme-shims.mjs — do not edit.\n` +
    `const m = window.__MESH_SHARED__[${JSON.stringify(key)}];\n` +
    `export default m.default ?? m;\n` +
    exports.map((n) => `export const ${n} = m.${n};`).join("\n") +
    "\n";
  const p = path.join(OUT, file);
  if (check) {
    if (!existsSync(p) || readFileSync(p, "utf8") !== body) {
      console.error(`stale: public/theme-shared/${file}`);
      stale++;
    }
  } else {
    mkdirSync(OUT, { recursive: true });
    writeFileSync(p, body);
  }
}
if (check) {
  const html = readFileSync(path.join(WEB, "index.html"), "utf8");
  const m = /<script type="importmap">([\s\S]*?)<\/script>/.exec(html);
  if (!m || JSON.stringify(JSON.parse(m[1])) !== JSON.stringify(IMPORT_MAP)) {
    console.error("stale: import map in index.html");
    stale++;
  }
  if (stale) process.exit(1);
  console.log("theme shims up to date");
}
